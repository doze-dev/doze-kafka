const (
	avroUser1 = `{"type":"record","name":"User","fields":[{"name":"id","type":"long"}]}`
	avroUser2 = `{"type":"record","name":"User","fields":[{"name":"id","type":"long"},{"name":"email","type":["null","string"],"default":null}]}`
	// avroUserBad adds a required field with no default: not backward compatible.
	avroUserBad = `{"type":"record","name":"User","fields":[{"name":"id","type":"long"},{"name":"email","type":"string"}]}`
	avroSpaced  = `{ "type" : "record", "name" : "User", "fields" : [ { "name" : "id", "type" : "long" } ] }`
	avroAddress = `{"type":"record","name":"Address","namespace":"com.acme","fields":[{"name":"city","type":"string"}]}`
	avroPerson  = `{"type":"record","name":"Person","namespace":"com.acme","fields":[{"name":"home","type":"com.acme.Address"}]}`

	jsonUser1 = `{"type":"object","properties":{"id":{"type":"integer"}},"required":["id"]}`
	jsonUser2 = `{"type":"object","properties":{"id":{"type":"integer"},"name":{"type":"string"}},"required":["id"]}`

	protoUser1 = `syntax = "proto3"; message User { int64 id = 1; }`
	protoUser2 = `syntax = "proto3"; message User { int64 id = 1; string name = 2; }`
)

func cleanupSubjects(names ...string) []scriptStep {
	var out []scriptStep
	for _, n := range names {
		out = append(out, del("/subjects/"+n), del("/subjects/"+n+"?permanent=true"), del("/config/"+n), del("/mode/"+n))
	}
	out = append(out, put("/config", `{"compatibility":"BACKWARD"}`), put("/mode", `{"mode":"READWRITE"}`))
	return out
}

